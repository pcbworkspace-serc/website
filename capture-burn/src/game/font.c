static int glyph_index(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    if (c < 32 || c > 95) c = '?';
    return c - 32;
}

void font_draw(SDL_Renderer *r, float x, float y, float s, const char *str)
{
    SDL_FRect rects[1024];
    int n = 0;
    float cx = x;
    for (const char *p = str; *p; p++) {
        if (*p == '\n') { cx = x; y += 9 * s; continue; }
        const char *g = GLYPHS[glyph_index(*p)];
        for (int i = 0; i < 35 && g[i]; i++) {
            if (g[i] != '#') continue;
            if (n == 1024) { SDL_RenderFillRectsF(r, rects, n); n = 0; }
            rects[n].x = cx + (float)(i % 5) * s;
            rects[n].y = y + (float)(i / 5) * s;
            rects[n].w = s;
            rects[n].h = s;
            n++;
        }
        cx += 6 * s;
    }
    if (n) SDL_RenderFillRectsF(r, rects, n);
}

float font_width(const char *s, float scale)
{
    int n = 0, best = 0;
    for (const char *p = s; *p; p++) {
        if (*p == '\n') { if (n > best) best = n; n = 0; continue; }
        n++;
    }
    if (n > best) best = n;
    return best ? (best * 6 - 1) * scale : 0;
}

void font_draw_centered(SDL_Renderer *r, float cx, float y, float scale, const char *s)
{
    font_draw(r, cx - font_width(s, scale) * 0.5f, y, scale, s);
}
